-- ---------------------------------------------------------------------
-- updated_at triggers
-- ---------------------------------------------------------------------
do $$
declare
  t text;
begin
  foreach t in array array[
    'users', 'trainer_profiles', 'membership_plans', 'memberships', 'payments', 'refunds',
    'trainer_assignments', 'trainer_availability', 'group_classes', 'class_bookings',
    'pt_sessions', 'session_notes', 'workout_plans', 'progress_logs', 'progress_photos',
    'health_questionnaires', 'messages', 'certifications', 'check_ins'
  ]
  loop
    execute format('drop trigger if exists set_updated_at on gym_v1.%I', t);
    execute format(
      'create trigger set_updated_at before update on gym_v1.%I
         for each row execute function gym_v1.set_updated_at()', t);
  end loop;
end;
$$;
